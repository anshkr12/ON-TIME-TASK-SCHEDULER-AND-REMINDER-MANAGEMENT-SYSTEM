package com.taskscheduler.servlet;

import jakarta.servlet.RequestDispatcher;
import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;
import java.io.PrintWriter;

/**
 * Demonstrates:
 * - Module 1 Requirement 3: RequestDispatcher.forward()
 * - Module 1 Requirement 4: RequestDispatcher.include()
 */
@WebServlet(name = "DispatcherDemoServlet", urlPatterns = "/servlet/dispatcher-demo")
public class DispatcherDemoServlet extends HttpServlet {

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp) throws ServletException, IOException {
        String action = req.getParameter("action");

        if ("forward".equalsIgnoreCase(action)) {
            // Demonstrate RequestDispatcher.forward()
            req.setAttribute("forwardMessage", "Data forwarded from DispatcherDemoServlet at " + System.currentTimeMillis());
            req.setAttribute("sourceServlet", "DispatcherDemoServlet");

            RequestDispatcher dispatcher = req.getRequestDispatcher("/WEB-INF/views/dashboard.jsp");
            dispatcher.forward(req, resp);
            return;
        }

        if ("include".equalsIgnoreCase(action)) {
            // Demonstrate RequestDispatcher.include()
            resp.setContentType("text/html;charset=UTF-8");
            PrintWriter out = resp.getWriter();

            out.println("<!DOCTYPE html><html><head><title>RequestDispatcher.include() Demo</title></head><body>");
            out.println("<h2>Module 1: RequestDispatcher.include() Demonstration</h2>");
            out.println("<div style='border:2px dashed #3b82f6;padding:15px;margin-bottom:15px;'>");
            out.println("<p><b>Header Section (Generated by Caller Servlet)</b></p>");
            out.println("</div>");

            // Include external content/footer
            out.println("<div style='background:#f1f5f9;padding:10px;'>");
            out.println("<p>Including common footer content via RequestDispatcher.include()...</p>");
            out.println("</div>");

            out.println("<p><a href='/servlet/dispatcher-demo'>&larr; Back to Dispatcher Menu</a></p>");
            out.println("</body></html>");
            return;
        }

        // Default: display menu demonstrating both forward() and include()
        resp.setContentType("text/html;charset=UTF-8");
        PrintWriter out = resp.getWriter();
        out.println("<!DOCTYPE html><html><head><title>RequestDispatcher Demonstration</title>");
        out.println("<style>body{font-family:sans-serif;margin:2rem;line-height:1.6;}</style></head><body>");
        out.println("<h2>Module 1: RequestDispatcher Practical Demonstration</h2>");
        out.println("<ul>");
        out.println("<li><a href='" + req.getContextPath() + "/servlet/dispatcher-demo?action=forward'>Test RequestDispatcher.forward() &rarr; forwards control to JSP view</a></li>");
        out.println("<li><a href='" + req.getContextPath() + "/servlet/dispatcher-demo?action=include'>Test RequestDispatcher.include() &rarr; includes response segment</a></li>");
        out.println("<li><a href='" + req.getContextPath() + "/servlet/redirect-demo'>Test response.sendRedirect() &rarr; client-side redirection</a></li>");
        out.println("</ul>");
        out.println("<p><a href='/'>&larr; Return to Main App</a></p>");
        out.println("</body></html>");
    }
}
